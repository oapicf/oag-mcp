"use strict";
/**
 * Artifact layout, manifest integrity and the files written alongside the
 * prepared SDK.
 *
 * @module build/artifact
 */
import fs from "node:fs";
import path from "node:path";

import { OagMcpError } from "../errors.js";
import type { ArtifactManifest, MethodRecord } from "../types.js";
import { listFiles, sha256File } from "../util/hash.js";
import { ARTIFACT_FORMAT_VERSION } from "../version.js";

/** Manifest file name at the artifact root. */
export const MANIFEST_FILE = "oag-mcp-manifest.json";

/** Relative paths inside an artifact. */
export const ARTIFACT_PATHS = {
  methods: "index/methods.json",
  searchIndex: "index/search-index.json",
  bundle: "sdk/sdk.bundle.js",
  types: "sdk/types",
  binding: "sdk/sdk-binding.d.ts",
  tsLib: "sdk/ts-lib",
  runner: "executor/runner.js",
  sdkPackage: "sdk-package",
} as const;

/** Paths excluded from integrity hashing. */
function _excluded(rel: string): boolean {
  return (
    rel === MANIFEST_FILE ||
    rel.startsWith(`${ARTIFACT_PATHS.sdkPackage}/`) ||
    rel.startsWith("node_modules/") ||
    rel === "package-lock.json"
  );
}

/**
 * Compute integrity hashes of artifact files.
 *
 * @param {String} dir - artifact directory
 * @return {Object} relative path -> sha256
 */
export function hashArtifactFiles(dir: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const rel of listFiles(dir, (r) => !r.startsWith("node_modules"))) {
    if (!_excluded(rel)) {
      out[rel] = sha256File(path.join(dir, rel));
    }
  }
  return out;
}

/**
 * Generate the TypeScript declaration of the `sdk` binding.
 *
 * @param {Array} records - method records
 * @return {String} declaration source
 */
export function bindingDeclaration(records: MethodRecord[]): string {
  const byClass = new Map<string, string[]>();
  for (const r of records) {
    byClass.set(r.className, [
      ...(byClass.get(r.className) ?? []),
      r.methodName,
    ]);
  }
  const lines = [
    "// Generated by oag-mcp. Declares the `sdk` binding available to execute code.",
    'import type * as __sdk from "./types/index";',
    "",
    "declare global {",
    "  /**",
    "   * SDK binding provided by oag-mcp: `sdk.<ApiClass>.<method>(...)` calls the",
    "   * generated typescript-fetch SDK. Base URL and credentials are configured",
    "   * by the server; do not pass them.",
    "   */",
    "  const sdk: {",
  ];
  for (const [cls, methods] of [...byClass.entries()].sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const names = methods
      .sort()
      .map((m) => JSON.stringify(m))
      .join(" | ");
    lines.push(`    readonly ${cls}: Pick<__sdk.${cls}, ${names}>;`);
  }
  lines.push("  };", "}", "", "export {};", "");
  return lines.join("\n");
}

/**
 * Validate an artifact directory: manifest format and file integrity.
 *
 * @param {String} dir - artifact directory
 * @return {Object} manifest
 */
export function readAndVerifyManifest(dir: string): ArtifactManifest {
  const file = path.join(dir, MANIFEST_FILE);
  if (!fs.existsSync(file)) {
    throw new OagMcpError(
      "ARTIFACT_NOT_FOUND",
      `${dir} is not an oag-mcp artifact (missing ${MANIFEST_FILE})`,
      { hint: "Create one with `oag-mcp build --spec ... --out <dir>`." },
    );
  }
  let manifest: ArtifactManifest;
  try {
    manifest = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (err) {
    throw new OagMcpError(
      "ARTIFACT_INVALID",
      `${MANIFEST_FILE} is not valid JSON`,
      {
        cause: err,
      },
    );
  }
  if (manifest.format !== "oag-mcp-artifact") {
    throw new OagMcpError(
      "ARTIFACT_INVALID",
      `${MANIFEST_FILE} has an unknown format`,
    );
  }
  if (manifest.formatVersion !== ARTIFACT_FORMAT_VERSION) {
    throw new OagMcpError(
      "ARTIFACT_VERSION_UNSUPPORTED",
      `Artifact format ${manifest.formatVersion} is not supported by this oag-mcp (expects ${ARTIFACT_FORMAT_VERSION})`,
      { hint: "Rebuild the artifact with this oag-mcp version." },
    );
  }
  const problems: string[] = [];
  for (const [rel, expected] of Object.entries(manifest.files ?? {})) {
    const abs = path.join(dir, rel);
    if (!fs.existsSync(abs)) {
      problems.push(`${rel}: missing`);
    } else if (sha256File(abs) !== expected) {
      problems.push(`${rel}: modified`);
    }
  }
  for (const required of [
    ARTIFACT_PATHS.methods,
    ARTIFACT_PATHS.bundle,
    ARTIFACT_PATHS.runner,
    ARTIFACT_PATHS.binding,
  ]) {
    if (!manifest.files?.[required]) {
      problems.push(`${required}: not recorded in manifest`);
    }
  }
  if (problems.length > 0) {
    throw new OagMcpError(
      "ARTIFACT_INTEGRITY",
      `Artifact ${dir} failed integrity checks: ${problems.slice(0, 5).join("; ")}`,
      {
        hint: "Rebuild the artifact; do not edit files inside it.",
        details: { problems },
      },
    );
  }
  return manifest;
}

/**
 * README written into each artifact.
 *
 * @param {Object} manifest - manifest
 * @return {String} markdown
 */
export function artifactReadme(manifest: ArtifactManifest): string {
  return `# ${manifest.api.title} — oag-mcp server

This directory is an [oag-mcp](https://github.com/oapicf/oag-mcp) artifact:
a prepared ${manifest.target.generator} SDK (OpenAPI Generator ${manifest.target.oagVersion}),
its searchable method index, type declarations and the sandbox executor.

It does not need the original OpenAPI document or SDK directory, Java, Docker,
or any package installation per request. It contains no secrets.

## Run

\`\`\`bash
# with oag-mcp installed globally
oag-mcp serve . --transport stdio
oag-mcp serve . --transport streamable-http --port 3000

# or install the pinned runtime next to the artifact once, then run it
npm install --omit=dev
npx oag-mcp serve . --transport stdio
\`\`\`

Upstream credentials and MCP access control are supplied at runtime with
\`--config <file>\`; see the oag-mcp documentation.

Build: ${manifest.buildId} (${manifest.createdAt}), ${manifest.operations.length} SDK methods.
`;
}
